    static readonly bool SystemEnglish = CultureInfo.CurrentUICulture.TwoLetterISOLanguageName != "zh";
    static bool english = SystemEnglish;
    static string language = "auto";

    public static bool IsEnglish => Volatile.Read(ref english);
    public static string Language => Volatile.Read(ref language);

    public static void UseLanguage(string? value)
    {
        string selected = NormalizeLanguage(value);
        Volatile.Write(ref language, selected);
        Volatile.Write(ref english, selected == "en" || selected == "auto" && SystemEnglish);
    }

    public static string NormalizeLanguage(string? value) =>
        string.Equals(value, "en", StringComparison.OrdinalIgnoreCase) ? "en" :
        string.Equals(value, "zh-CN", StringComparison.OrdinalIgnoreCase) ? "zh-CN" : "auto";

    public static string T(string text) => IsEnglish && English.TryGetValue(text, out var translated) ? translated : text;
    public static bool HasTranslation(string text) => English.ContainsKey(text);
    public static string Format(string text, params object[] args) => string.Format(CultureInfo.CurrentCulture, T(text), args);

